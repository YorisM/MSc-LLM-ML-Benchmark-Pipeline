class MyPreprocessor:
    def __init__(self):
        pass

    def fit(self, X, y=None):
        return self

    def transform(self, X):
        # Reshape the data to separate objects and their features
        X = X.view(-1, 18, 5)  # 18 objects, 5 features each
        # Calculate derived features: transverse mass, energy squared, and pseudorapidity squared
        obj_E = X[:, :, 1]  # Energy
        obj_pt = X[:, :, 2]  # pT
        obj_eta = X[:, :, 3]  # eta
        obj_phi = X[:, :, 4]  # phi
        obj_px = obj_pt * torch.cos(obj_phi)  # px
        obj_py = obj_pt * torch.sin(obj_phi)  # py
        obj_pz = obj_pt * torch.sinh(obj_eta)  # pz
        X = torch.cat((X[:, :, :1], obj_px.unsqueeze(-1), obj_py.unsqueeze(-1), obj_pz.unsqueeze(-1), X[:, :, 2:]), dim=-1)
        X = X.view(X.size(0), -1)  # Flatten
        # Concatenate E_T_miss and phi_{E_t}_miss
        X = torch.cat((X, X_train[:, :2]), dim=-1)  # Assuming X_train is accessible here, but it should be the input X
        return X

    def fit_transform(self, X, y=None):
        self.fit(X, y)
        return self.transform(X)

def make_preprocessor():
    return MyPreprocessor()

def make_model(input_dim: int):
    model = nn.Sequential(
        nn.Linear(input_dim, 128),
        nn.ReLU(),
        nn.Dropout(0.2),
        nn.Linear(128, 64),
        nn.ReLU(),
        nn.Dropout(0.2),
        nn.Linear(64, 1),
        nn.Sigmoid()
    )
    return model

EPOCHS = 10

def train_model(model, train_loader, val_loader, epochs):
    criterion = nn.BCELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
    train_loss, val_loss, train_acc, val_acc = [], [], [], []
    for epoch in range(epochs):
        model.train()
        total_loss, total_correct = 0, 0
        for X_batch, y_batch in train_loader:
            optimizer.zero_grad()
            outputs = model(X_batch)
            loss = criterion(outputs, y_batch.float().unsqueeze(-1))
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
            total_correct += ((outputs > 0.5) == y_batch.unsqueeze(-1)).sum().item()
        train_loss.append(total_loss / len(train_loader))
        train_acc.append(total_correct / len(train_loader.dataset))
        model.eval()
        val_loss_epoch, val_acc_epoch = 0, 0
        with torch.no_grad():
            total_val_correct = 0
            total_val_loss = 0
            for X_val_batch, y_val_batch in val_loader:
                outputs = model(X_val_batch)
                loss = criterion(outputs, y_val_batch.float().unsqueeze(-1))
                total_val_loss += loss.item()
                total_val_correct += ((outputs > 0.5) == y_val_batch.unsqueeze(-1)).sum().item()
            val_loss_epoch = total_val_loss / len(val_loader)
            val_acc_epoch = total_val_correct / len(val_loader.dataset)
        val_loss.append(val_loss_epoch)
        val_acc.append(val_acc_epoch)
    return model, train_loss, val_loss, train_acc, val_acc

